        /// <summary>
        /// 获取提示信息, 如果存在错误提示否则会返回错误代码
        /// </summary>
        /// <param name="lang">语系</param>
        /// <param name="code">提示代码</param>
        /// <returns></returns>
        public static string QueryMessage(string lang, string code) {
            if (lang.Equals("vn"))
                return codes_vn.ContainsKey(code) ? codes_vn[code] : code;
            else if (lang.Equals("cs"))
                return codes_cs.ContainsKey(code) ? codes_cs[code] : code;
            else
                return code;
        }

